main:
 GPU_load GPU_sp, puro_frames
 GPU_load GPU_X, 0
 GPU_push GPU_X
 .loop:
  GPU_rmem GPU_Y, GPU_sp
  GPU_mov  GPU_R, GPU_Y
  GPU_addi GPU_sp, 1, GPU_sp
  GPU_rmem GPU_Y, GPU_sp
  GPU_mov  GPU_G, GPU_Y
  GPU_addi GPU_sp, 1, GPU_sp
  GPU_rmem GPU_Y, GPU_sp
  GPU_mov  GPU_B, GPU_Y
  GPU_addi GPU_sp, 1, GPU_sp
  GPU_palt PALETTE_WRITE, GPU_X
  GPU_addi GPU_X, 1, GPU_X
  GPU_cmplti GPU_X, 15, 1
   GPU_load GPU_IP, .loop
 ;
 GPU_rmemi  GPU_X,  CPLength+4   ;grabbing resolution width
 GPU_rmemi  GPU_X2, CPLength+4+1
 GPU_bsli   GPU_X,  8,      GPU_X
 GPU_or     GPU_X,  GPU_X2, GPU_X2
 ;
 GPU_rmemi  GPU_X,  CPLength+6    ;grabbing resolution height
 GPU_rmemi  GPU_Y2, CPLength+6+1
 GPU_bsli   GPU_X,  8,      GPU_X
 GPU_or     GPU_X,  GPU_Y2, GPU_Y2
 ;
 GPU_load GPU_X, 0
 GPU_load GPU_Y, 0
 ;
 GPU_setout
 GPU_sprite SPRITE_CP ; uses SpritePointer
 GPU_render ; renders layer 4 to screen
 ;
 GPU_addi GPU_sp, 86400, GPU_sp
 ;
 .delay:
  GPU_render ; renders layer 4 to screen
  GPU_clk GPU_Y
  GPU_cmplt GPU_Y, 30, 2
   GPU_clk GPU_Y, 1
   GPU_load GPU_IP, .delay
 ;
 GPU_pop GPU_X
 GPU_addi GPU_X, 1, GPU_X
 GPU_cmpgti GPU_X, 21, 1
  GPU_load GPU_IP, main
 GPU_push GPU_X
 GPU_load GPU_X, 0
 GPU_load GPU_IP, .loop
 ;
